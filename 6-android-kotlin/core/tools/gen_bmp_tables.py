#!/usr/bin/env python3
"""Generate the BMP parity reference table and the Kotlin lookup tables from CPython (stdlib only).

Run from the 6-android-kotlin project root:

    python3 core/tools/gen_bmp_tables.py

One pass over U+0000..U+FFFF and one over U+10000..U+10FFFF write three files:

  core/src/test/resources/bmp_python.tsv
      One row per BMP code point: codepoint hex, str.isspace() as 0/1, and
      str.upper() as UTF-16BE hex. The Kotlin BmpParityTest compares the port
      against this table for every row and fails on any mismatch.

  core/src/test/resources/supplementary_upper_python.tsv
      One row per supplementary code point whose str.upper() is not the
      identity: codepoint hex and the single code point it uppercases to. The
      Kotlin SupplementaryUpperParityTest compares the port against every row.

  core/src/main/kotlin/org/everlang/dna/PyUnicodeTables.kt
      The same facts as compact lookup tables for the port.

The port embeds these tables instead of calling java.lang.Character or
String.toUpperCase. JDK and Android ICU Unicode data differ from CPython's
(CPython 3.13 here uses unicodedata 15.1.0), and the Android platform data
varies by device version. Embedding makes the behavior independent of the
runtime.

Supplementary code points (U+10000 and up) are checked for the facts the port
relies on, and the script aborts if any of them stops holding: no supplementary
code point is whitespace, every supplementary upper() is one code point, and
none uppercases to A, T, C or G. Their upper() mappings are written in full, as
the BMP ones are, so the port's upper() matches CPython on every code point.
"""

import sys
import unicodedata
from pathlib import Path

CORE = Path(__file__).resolve().parent.parent
TSV_OUT = CORE / "src" / "test" / "resources" / "bmp_python.tsv"
SUPP_TSV_OUT = CORE / "src" / "test" / "resources" / "supplementary_upper_python.tsv"
KT_OUT = CORE / "src" / "main" / "kotlin" / "org" / "everlang" / "dna" / "PyUnicodeTables.kt"
TSV_HEADER = "codepoint\tisspace\tupper_utf16be_hex"
SUPP_TSV_HEADER = "codepoint\tupper_codepoint"
PER_LINE = 8


def require(condition, message):
    if not condition:
        raise SystemExit(f"gen_bmp_tables: {message}")


def utf16be_hex(text):
    return text.encode("utf-16-be", "surrogatepass").hex()


def check_supplementary():
    for cp in range(0x10000, 0x110000):
        ch = chr(cp)
        require(not ch.isspace(), f"supplementary U+{cp:04X} is whitespace")
        up = ch.upper()
        require(len(up) == 1, f"supplementary U+{cp:04X} upper() is multi-char")
        require(ord(up) >= 0x10000, f"supplementary U+{cp:04X} uppercases into the BMP")
        require(up not in ("A", "T", "C", "G"), f"supplementary U+{cp:04X} uppercases to ATCG")


def collect():
    rows = [TSV_HEADER]
    space = []
    upper_items = []
    for cp in range(0x10000):
        ch = chr(cp)
        is_space = ch.isspace()
        up = ch.upper()
        rows.append(f"{cp:04X}\t{int(is_space)}\t{utf16be_hex(up)}")
        if is_space:
            space.append(cp)
        if up != ch:
            upper_items.append((cp, up))
    for cp, up in upper_items:
        require(all(ord(c) <= 0xFFFF for c in up), f"U+{cp:04X} upper() leaves the BMP")
        require(not any(0xD800 <= ord(c) <= 0xDFFF for c in up), f"U+{cp:04X} upper() yields a surrogate")
    return rows, space, upper_items


def supplementary_upper_items():
    """(codepoint, upper codepoint) for every supplementary code point that str.upper() changes."""
    items = []
    for cp in range(0x10000, 0x110000):
        ch = chr(cp)
        up = ch.upper()
        if up != ch:
            items.append((cp, ord(up)))
    return items


def hex_literals(values):
    return [f"0x{v:04X}" for v in values]


def chunked(items, size):
    for start in range(0, len(items), size):
        yield items[start:start + size]


def kotlin_source(space, upper_items, supp_items):
    lines = [
        f"// GENERATED by core/tools/gen_bmp_tables.py from CPython {sys.version.split()[0]} "
        f"(unicodedata {unicodedata.unidata_version}). Do not edit by hand.",
        "",
        "package org.everlang.dna",
        "",
        "/**",
        " * CPython str.isspace() and str.upper() over the BMP, as lookup tables.",
        " *",
        " * Multi-character upper() results (for example U+00DF -> \"SS\", U+FB05 -> \"ST\",",
        " * U+1E9A -> \"A\" + U+02BE) are stored in full, so the port matches CPython's full case",
        " * mapping. Supplementary code points are listed only where str.upper() changes them: the",
        " * generator verified that none is whitespace, none uppercases to A, T, C or G, and each",
        " * uppercases to one code point.",
        " */",
        "internal object PyUnicodeTables {",
        "    /** Ascending BMP code points for which str.isspace() is true (29 entries). */",
        "    val SPACE: IntArray = intArrayOf(",
    ]
    for chunk in chunked(hex_literals(space), PER_LINE):
        lines.append("        " + ", ".join(chunk) + ",")
    lines.append("    )")
    lines.append("")
    lines.append("    /** Ascending BMP code points whose str.upper() is not the identity. */")
    lines.append("    val UPPER_KEYS: IntArray = intArrayOf(")
    for chunk in chunked(hex_literals([cp for cp, _ in upper_items]), PER_LINE):
        lines.append("        " + ", ".join(chunk) + ",")
    lines.append("    )")
    lines.append("")
    lines.append("    /** UPPER_VALUES[i] is str.upper() of UPPER_KEYS[i], as UTF-16 code units. */")
    lines.append("    val UPPER_VALUES: Array<String> = arrayOf(")
    for _, up in upper_items:
        escaped = "".join(f"\\u{ord(c):04X}" for c in up)
        lines.append(f'        "{escaped}",')
    lines.append("    )")
    lines.append("")
    lines.append("    /** Ascending supplementary code points whose str.upper() is not the identity. */")
    lines.append("    val SUPPLEMENTARY_UPPER_KEYS: IntArray = intArrayOf(")
    for chunk in chunked(hex_literals([cp for cp, _ in supp_items]), PER_LINE):
        lines.append("        " + ", ".join(chunk) + ",")
    lines.append("    )")
    lines.append("")
    lines.append("    /** SUPPLEMENTARY_UPPER_VALUES[i] is the one code point that str.upper() gives SUPPLEMENTARY_UPPER_KEYS[i]. */")
    lines.append("    val SUPPLEMENTARY_UPPER_VALUES: IntArray = intArrayOf(")
    for chunk in chunked(hex_literals([up for _, up in supp_items]), PER_LINE):
        lines.append("        " + ", ".join(chunk) + ",")
    lines.append("    )")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def supplementary_tsv(supp_items):
    rows = [SUPP_TSV_HEADER]
    rows.extend(f"{cp:04X}\t{up:04X}" for cp, up in supp_items)
    return rows


def main():
    check_supplementary()
    rows, space, upper_items = collect()
    supp_items = supplementary_upper_items()
    require(len(space) == 29, f"expected 29 BMP whitespace code points, found {len(space)}")
    require(len(supp_items) > 0, "no supplementary upper() mappings found")
    TSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    KT_OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(TSV_OUT, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(rows) + "\n")
    with open(SUPP_TSV_OUT, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(supplementary_tsv(supp_items)) + "\n")
    with open(KT_OUT, "w", encoding="ascii", newline="\n") as fh:
        fh.write(kotlin_source(space, upper_items, supp_items))
    print(f"wrote {TSV_OUT} rows={len(rows) - 1}")
    print(f"wrote {SUPP_TSV_OUT} rows={len(supp_items)}")
    print(f"wrote {KT_OUT} space={len(space)} upper_entries={len(upper_items)} supplementary_upper_entries={len(supp_items)}")


if __name__ == "__main__":
    main()
